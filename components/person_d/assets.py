"""SHA-256 checks for Person D reference assets.

Standard library only, so ``verify_assets`` can check ``reference/person_d/``
before any model framework is installed.
"""

from __future__ import annotations

import hashlib
import os
import re
from pathlib import Path
from typing import Any, List, Mapping, Union


SHA256_PATTERN = re.compile(r"[0-9a-f]{64}")
EXAMPLE_IMAGE_EXTENSIONS = {".jpg", ".jpeg", ".png", ".tif", ".tiff", ".bmp", ".webp"}
# PLIP loads with from_pretrained, so these snapshot files shape the model input as well.
PLIP_SUPPORT_FILES = (
    "config.json",
    "preprocessor_config.json",
    "special_tokens_map.json",
    "tokenizer.json",
    "tokenizer_config.json",
)


def file_sha256(path: Union[str, Path]) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def tree_files(root: Path) -> list[tuple[str, str]]:
    """Return ``(relative-posix-path, absolute-path)`` of every file below ``root``, sorted by path.

    The walk starts from the resolved root and, on Windows, uses the extended-length prefix, so
    a deep tree is never silently truncated at MAX_PATH.
    """

    base = str(root.resolve())
    if os.name == "nt" and not base.startswith("\\\\"):
        base = "\\\\?\\" + base
    files = [
        (os.path.relpath(os.path.join(directory, name), base).replace(os.sep, "/"), os.path.join(directory, name))
        for directory, _, names in os.walk(base)
        for name in names
    ]
    return sorted(files)


def tree_sha256(root: Path) -> tuple[int, str]:
    """Return the file count and the tree hash used in ``external-assets.yaml``.

    The tree hash is the SHA-256 of the newline-joined ``<file-sha256>  <relative-posix-path>``
    lines, sorted by the case-sensitive relative path.
    """

    files = tree_files(root)
    lines = [f"{file_sha256(path)}  {relative}" for relative, path in files]
    return len(files), hashlib.sha256("\n".join(lines).encode("utf-8")).hexdigest()


def sanitize_folder_name(name: str) -> str:
    name = name.strip()
    name = name.replace("/", "_")
    name = re.sub(r'[\:*?"<>|]', "_", name)
    name = re.sub(r"\s+", " ", name)
    return name


def sanitize_example_folder_name(name: str) -> str:
    """
    Convert ROI option labels to the folder style used by ./Example.

    Examples:
        N/A                         -> N_A
        Low-grade/Mild              -> Low-grade_Mild
        Coarsely clumped            -> Coarsely_clumped
        thin/stretched bridge       -> thin_stretched_bridge
        Fine pleomorphic/Clustered  -> Fine_pleomorphic_Clustered
    """
    name = str(name).strip()
    name = name.replace("/", "_")
    name = re.sub(r'[\:*?"<>|]', "_", name)
    name = re.sub(r"\s+", "_", name)
    name = re.sub(r"_+", "_", name)
    return name


def get_example_option_folder_candidates(option: str) -> List[str]:
    """
    Try several folder-name variants so the code can read both your Example style
    and the output-folder style generated by sanitize_folder_name().
    """
    candidates = [
        str(option).strip(),
        sanitize_example_folder_name(option),
        sanitize_folder_name(option),
    ]

    # Some previous output folders may keep spaces after replacing slash.
    candidates.append(sanitize_folder_name(option).replace(" ", "_"))

    # Deduplicate while preserving order.
    seen = set()
    unique_candidates = []
    for candidate in candidates:
        if candidate and candidate not in seen:
            unique_candidates.append(candidate)
            seen.add(candidate)

    return unique_candidates


def example_layout(
    root: Path, attributes: Mapping[str, Mapping[str, List[str]]]
) -> tuple[int, int, list[str]]:
    """Return the file count, the count the prototype loader uses, and the files it ignores.

    The loader reads ``<group>/<attribute>/<option folder>/`` for every vocabulary option, taking
    the first existing folder-name candidate and every image file below it.  Folder names are
    compared case-sensitively, as on the Linux image.
    """

    files = [relative for relative, _ in tree_files(root)]
    existing = {"/".join(relative.split("/")[:3]) for relative in files if relative.count("/") >= 3}
    option_dirs = set()
    for group, attrs in attributes.items():
        for attribute, options in attrs.items():
            for option in options:
                for name in get_example_option_folder_candidates(option):
                    if f"{group}/{attribute}/{name}" in existing:
                        option_dirs.add(f"{group}/{attribute}/{name}")
                        break
    ignored = [
        relative
        for relative in files
        if "/".join(relative.split("/")[:3]) not in option_dirs
        or os.path.splitext(relative)[1].lower() not in EXAMPLE_IMAGE_EXTENSIONS
    ]
    return len(files), len(files) - len(ignored), ignored


def validate_example_layout(
    root: Path, attributes: Mapping[str, Mapping[str, List[str]]]
) -> tuple[int, int]:
    """Fail when the example tree holds a file the prototype loader would silently ignore."""

    count, usable, ignored = example_layout(root, attributes)
    if ignored:
        shown = ", ".join(ignored[:5]) + (" ..." if len(ignored) > 5 else "")
        raise ValueError(
            f"Person D example tree has {len(ignored)} file(s) outside a recognised "
            f"<group>/<attribute>/<option>/ image folder: {shown}"
        )
    return count, usable


def required_digest(config: dict[str, Any], key: str, owner: str) -> str:
    value = config.get(key)
    if not isinstance(value, str) or not SHA256_PATTERN.fullmatch(value):
        raise ValueError(f"Person D {owner} config requires {key} as a lowercase SHA-256 hex digest")
    return value


def required_digests(config: dict[str, Any], key: str, names: tuple[str, ...], owner: str) -> dict[str, str]:
    """Return ``config[key]`` when it pins exactly ``names`` to SHA-256 digests."""

    value = config.get(key)
    if (
        not isinstance(value, dict)
        or set(value) != set(names)
        or any(not isinstance(digest, str) or not SHA256_PATTERN.fullmatch(digest) for digest in value.values())
    ):
        raise ValueError(
            f"Person D {owner} config requires {key} with a lowercase SHA-256 hex digest for each of {list(names)}"
        )
    return value


def check_digest(actual: str, expected: str, label: str) -> None:
    if actual != expected:
        raise ValueError(f"{label} SHA-256 mismatch: expected {expected}, got {actual}")
